"""Everything computed after generation, from saved text.

The sweeps record and score nothing. This reads their output and produces four
things, none of which needs a GPU and none of which can therefore cost a
generation run when it breaks.

**Quality.** ROUGE-L always; BERTScore when the package can load its model.

**Where the answer sits between the poles.** The objection to a quality gain is
that less DP trivially means better text, and a system ignoring every document
would also score well. So each routed answer is compared against two references
generated by `stage3_poles.py` on the same documents: one with no documents, one
with all of them. Leaning towards the all-document pole is evidence the documents
still shape the answer; leaning towards the no-document pole means the method is
merely not doing RAG. **Read this before quoting any quality number.**

**Whether the epsilon that was spent bought anything.** At a paid position the
aggregation may still emit the token NoRAG would have chosen -- in which case the
budget went on a position the pre-filter could have skipped. The share of paid
positions where the emitted token differs from `norag_argmax` is how much of the
spend was productive, and it is available only because both sequences are stored.

**Where the clinical content came from.** For each clinical span in the answer,
does that text appear in any retrieved document? Content the documents support is
grounded; content they do not is the model's prior speaking, which is the medical
risk Stage 2.5 exists to watch.

    uv run python experiments/stage3_score.py
"""

import glob
import math
import statistics as st
import sys

from dprag import paths, run_record, trace
from dprag.chatdoctor import load_corpus, load_queries
from dprag.config import ExperimentConfig
from dprag.medical_flags import WORD_KIND
from dprag.quality import rouge_l_f1

RECORD_GLOB = "stage3_*"
POLES_GLOB = "stage3_poles_*"


def ci95(values: list[float]) -> tuple[float, float]:
    """Mean and half-width. A mean without one invites reading noise as a result."""
    if len(values) < 2:
        return (values[0] if values else 0.0), 0.0
    return st.mean(values), 1.96 * st.stdev(values) / math.sqrt(len(values))


def load_poles() -> dict[str, dict]:
    """query -> {norag_text, rag_text}. Empty if the poles have not been run."""
    found = sorted(glob.glob(str(paths.results_dir() / f"{POLES_GLOB}.json")))
    if not found:
        return {}
    record = run_record.load(found[-1])
    return {r["query"]: r for r in record.per_item}


def pole_lean(text: str, poles: dict) -> float | None:
    """How much more the answer resembles the all-document pole than the other.

    Positive: closer to the grounded end. Negative: the answer could have been
    written without retrieving anything, which is what the objection claims.
    """
    if not poles:
        return None
    return rouge_l_f1(text, poles["rag_text"]) - rouge_l_f1(text, poles["norag_text"])


def paid_productivity(strategy_record: dict) -> float | None:
    """Share of paid positions whose token differs from NoRAG's argmax.

    1.0 means every unit of epsilon changed the output. Near 0 means the budget was
    spent reproducing what the free path would have emitted anyway -- positions the
    pre-filter should have caught.
    """
    paid = strategy_record.get("paid_positions")
    emitted, norag = strategy_record.get("emitted"), strategy_record.get("norag_argmax")
    if not paid or not emitted or not norag:
        return None
    changed = sum(1 for i in paid if i < len(norag) and emitted[i] != norag[i])
    return changed / len(paid)


def grounding(strategy_record: dict, documents: list[str]) -> tuple[int, int]:
    """(clinical spans supported by a document, clinical spans total).

    Word-like spans only: a vocabulary has vetted those, whereas nothing can vet
    whether "197 mg" is a real dose, so counting doses here would measure the
    detector rather than the grounding.
    """
    text = strategy_record.get("text", "")
    clinical = strategy_record.get("clinical") or []
    if not text or not clinical or not documents:
        return 0, 0

    from dprag.medical_flags import find_medical_spans

    haystack = "\n".join(documents).lower()
    spans = [s for s in find_medical_spans(text) if s.kind == WORD_KIND]
    supported = sum(1 for s in spans if s.text.lower() in haystack)
    return supported, len(spans)


def main():
    exp = ExperimentConfig()
    refs = {q.query: q.reference
            for q in load_queries(n=exp.n_queries, seed=exp.query_seed)}
    poles = load_poles()
    if not poles:
        print("!! No poles record found. Quality numbers below cannot be told apart")
        print("!! from 'we did less RAG'. Run experiments/stage3_poles.py.\n")

    corpus_cache: dict[tuple, list[str]] = {}
    paths_found = sorted(glob.glob(str(paths.results_dir() / f"{RECORD_GLOB}.json")))
    paths_found = [p for p in paths_found if "poles" not in p]
    if not paths_found:
        raise SystemExit("no stage3_* records found; run a phase first")

    print(f"{'record':>34} | {'config':>12} | {'ROUGE-L':>16} | "
          f"{'lean':>8} | {'eps used':>8} | {'grounded':>9}")
    print("-" * 104)

    for path in paths_found:
        record = run_record.load(path)
        key = (record.param("n_docs"), record.param("corpus_seed"))
        if key not in corpus_cache:
            corpus_cache[key] = load_corpus(limit=key[0], sample_seed=key[1])
        corpus = corpus_cache[key]

        names = record.metric("strategies", [])
        for name in names:
            quality, leans, productive = [], [], []
            supported = total_spans = 0
            for row in record.per_item:
                sr = row["by_strategy"].get(name)
                if not sr:
                    continue
                ref = refs.get(row["query"])
                if ref:
                    quality.append(rouge_l_f1(sr["text"], ref))
                if row["query"] in poles:
                    lean = pole_lean(sr["text"], poles[row["query"]])
                    if lean is not None:
                        leans.append(lean)
                p = paid_productivity(sr)
                if p is not None:
                    productive.append(p)
                docs = [corpus[i] for i, _ in row.get("docs", []) if i < len(corpus)]
                s, t = grounding(sr, docs)
                supported += s
                total_spans += t

            m, h = ci95(quality)
            lean_txt = ("%+.4f" % st.mean(leans)) if leans else "  n/a"
            prod_txt = ("%.1f%%" % (100 * st.mean(productive))) if productive else " n/a"
            ground_txt = ("%d/%d" % (supported, total_spans)) if total_spans else "  0/0"
            print(f"{record.path.stem[:34]:>34} | {name:>12} | "
                  f"{m:.4f} +-{h:.4f} | {lean_txt:>8} | {prod_txt:>8} | "
                  f"{ground_txt:>9}")

    print()
    print("ROUGE-L  mean with a 95% half-width. Overlapping intervals mean the two")
    print("         configurations are not distinguishable at this sample size --")
    print("         state the detectable difference, or 'no change' says nothing.")
    print("lean     ROUGE-L against the all-document pole minus the no-document one.")
    print("         Positive: the documents still shape the answer. Negative or near")
    print("         zero: the answer did not need retrieval, and a quality gain is")
    print("         indistinguishable from having skipped RAG.")
    print("eps used share of PAID positions whose token differed from NoRAG's argmax.")
    print("         Low means budget went on positions the pre-filter could have")
    print("         skipped -- headroom, not a failure.")
    print("grounded clinical word spans that appear verbatim in a retrieved document,")
    print("         over all clinical word spans. The rest came from the model.")


if __name__ == "__main__":
    main()
