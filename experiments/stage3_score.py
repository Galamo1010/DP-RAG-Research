def quality_table(rows) -> None:
    print()
    print("=" * 104)
    print("  QUALITY -- the answer against the doctor's reply")
    print("=" * 104)
    print(f"{'record':>34} | {'config':>12} | {'n':>4} | {'ROUGE-L':>17} | "
          f"{'BERTScore':>17}")
    print("-" * 104)
    for row in rows:
        rm, rh = ci95(row["rouge"][REFERENCE])
        bm, bh = ci95(row["bert"][REFERENCE])
        bert = f"{bm:.4f} +-{bh:.4f}" if row["bert"][REFERENCE] else "n/a"
        print(f"{row['stem'][:34]:>34} | {row['config']:>12} | {row['n']:>4} | "
              f"{rm:.4f} +-{rh:.4f} | {bert:>17}")
    print()
    print("Both are depressed by damaged references (last section). The penalty is")
    print("the same for every configuration, so RELATIVE comparisons hold and")
    print("absolute values do not license a claim about how good the answers are.")


def grounding_table(rows) -> None:
    print()
    print("=" * 128)
    print("  GROUNDING -- where the answer sits between the no-document and "
          "all-document poles")
    print("=" * 128)
    print(f"{'record':>34} | {'config':>12} | {'R:NoRAG':>8} | {'R:RAG':>7} | "
          f"{'R:lean':>7} | {'B:NoRAG':>8} | {'B:RAG':>7} | {'B:lean':>7} | "
          f"{'eps used':>8} | {'grounded':>9}")
    print("-" * 128)
    for row in rows:
        cells = []
        for metric in ("rouge", "bert"):
            norag = mean_or_none(row[metric][NORAG])
            rag = mean_or_none(row[metric][RAG])
            lean = None if norag is None or rag is None else rag - norag
            cells += [fmt(norag, "%.4f"), fmt(rag, "%.4f"), fmt(lean, "%+.4f")]
        prod = "n/a" if row["productive"] is None else "%.1f%%" % (100 * row["productive"])
        s, t = row["grounded"]
        print(f"{row['stem'][:34]:>34} | {row['config']:>12} | "
              f"{cells[0]:>8} | {cells[1]:>7} | {cells[2]:>7} | "
              f"{cells[3]:>8} | {cells[4]:>7} | {cells[5]:>7} | "
              f"{prod:>8} | {('%d/%d' % (s, t)) if t else '0/0':>9}")
    print()
    print("R: / B:  ROUGE-L / BERTScore. NoRAG and RAG are similarity to each pole;")
    print("         lean is RAG minus NoRAG.")
    print("READ THE TWO SIMILARITIES, NOT ONLY THE LEAN. A skipped position emits")
    print("NoRAG's own token, so a high-trigger configuration is partly COPYING the")
    print("pole it is measured against, and its NoRAG column rises for that reason")
    print("alone. A negative lean therefore does not by itself mean the documents")
    print("stopped mattering -- check whether the RAG column fell, or the NoRAG")
    print("column merely rose.")
    print("eps used share of PAID positions whose token differed from NoRAG's argmax.")
    print("         Low means budget went on positions the pre-filter could have")
    print("         skipped -- headroom, not a failure.")
    print("grounded clinical word spans appearing verbatim in a retrieved document,")
    print("         over all clinical word spans. The rest came from the model.")


def dominance_tables(rows) -> None:
    groups: dict[tuple[str, float], list[dict]] = {}
    for row in rows:
        if row["bert"][REFERENCE] and row["trigger"] is not None:
            groups.setdefault((row["model"], row["epsilon"]), []).append(row)

    for (model, eps), group in sorted(groups.items()):
        print()
        print(f"=== trade-off: who is dominated | {model} | eps={eps:g} ===")
        print("A configuration is dominated when another gives at least as much")
        print("epsilon saving AND at least as much quality. The quality axis here is")
        print("BERTScore; ROUGE-L is shown but does not arbitrate.")
        print()
        print(f"{'config':>14} | {'n':>4} | {'trigger':>8} | {'BERTScore':>17} | "
              f"{'ROUGE-L':>17} | verdict")
        print("-" * 100)
        scored = []
        for row in group:
            bm, bh = ci95(row["bert"][REFERENCE])
            rm, rh = ci95(row["rouge"][REFERENCE])
            scored.append((row["config"], row["trigger"], bm, bh, rm, rh, row["n"]))
        for name, trig, bm, bh, rm, rh, n in sorted(scored, key=lambda r: -r[1]):
            # Dominance needs the quality gap to clear both intervals. Judging on
            # point estimates alone once declared A "dominated" over a 0.007 gap
            # while the half-widths were 0.011 -- a verdict the data cannot carry.
            dominated_by = [o for o, t2, q2, h2, _r, _rh, _n in scored
                            if o != name and t2 >= trig and (q2 - h2) > (bm + bh)]
            if dominated_by:
                verdict = "dominated by " + ", ".join(dominated_by[:2])
            else:
                beaten = any((q2 - h2) > (bm + bh)
                             for o, _t, q2, h2, _r, _rh, _n in scored if o != name)
                verdict = "frontier" if not beaten else "frontier (kept: saves more)"
            print(f"{name:>14} | {n:>4} | {trig:>7.1%} | {bm:.4f} +-{bh:.4f} | "
                  f"{rm:.4f} +-{rh:.4f} | {verdict}")
    print()
    print("Overlapping intervals mean the two configurations are not distinguishable")
    print("at this sample size. That is an honest 'undetermined', not a tie.")
    print("Trigger rate stands in for epsilon saving; the two are monotone but not")
    print("proportional -- PLD composition is concave, so skipping 87% of positions")
    print("saves 82% of the budget, not 87%. One table per (model, epsilon), because")
    print("a stronger model scores higher everywhere and a larger budget buys more")
    print("everywhere, so pooling either axis would read as the pre-filter winning")
    print("or losing when neither had anything to do with it.")


def damage_table(rows, damaged, n_queries) -> None:
    n_damaged = sum(1 for kinds in damaged.values() if kinds)
    print()
    print("=" * 104)
    print("  DAMAGED REFERENCES -- does excluding them change the quality numbers?")
    print("=" * 104)
    print(f"{n_damaged} of {n_queries} references in the query sample carry damage "
          f"({n_damaged / n_queries:.1%}).")
    print("docs/notes/reference-damage.md measured this for ROUGE-L and found a")
    print("1-2% relative gap, concluding that reporting the damage beats excluding")
    print("30% of the sample -- the excluded attachment cases skew towards imaging")
    print("presentations, so they are not a random 12.5%. The open question it")
    print("recorded was whether a SEMANTIC metric loses more when the reference is")
    print("missing a drug name. These two columns answer it.")
    print()
    print(f"{'record':>34} | {'config':>12} | {'ROUGE all':>9} | {'clean':>9} | "
          f"{'diff':>8} | {'BERT all':>9} | {'clean':>9} | {'diff':>8}")
    print("-" * 118)
    for row in rows:
        ra = mean_or_none(row["rouge"][REFERENCE])
        rc = mean_or_none(row["clean"]["rouge"])
        ba = mean_or_none(row["bert"][REFERENCE])
        bc = mean_or_none(row["clean"]["bert"])
        rd = None if ra is None or rc is None else rc - ra
        bd = None if ba is None or bc is None else bc - ba
        print(f"{row['stem'][:34]:>34} | {row['config']:>12} | "
              f"{fmt(ra):>9} | {fmt(rc):>9} | {fmt(rd, '%+.4f'):>8} | "
              f"{fmt(ba):>9} | {fmt(bc):>9} | {fmt(bd, '%+.4f'):>8}")
    print()
    print("diff = clean subset minus full sample. A large positive diff on BERTScore")
    print("but not ROUGE-L would mean the damage costs the semantic metric more, and")
    print("the note's 'measured and found not to matter' would have to be withdrawn")
    print("for BERTScore.")


