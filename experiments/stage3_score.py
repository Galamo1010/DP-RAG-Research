def load_poles() -> dict[str, dict[str, dict]]:
    """gen_model -> query -> {norag_text, rag_text}.

    Keyed by model, not by filename. The poles say what a *model* writes with and
    without the documents, so locating one model's answers against another
    model's poles is meaningless -- and it fails silently, producing a plausible
    lean rather than an error.
    """
    by_model: dict[str, dict[str, dict]] = {}
    for path in sorted(glob.glob(str(paths.results_dir() / f"{POLES_GLOB}.json"))):
        record = run_record.load(path)
        model = record.metric("gen_model") or record.param("gen_model")
        if model is None:
            print(f"!! {record.path.stem} names no model and cannot be matched to "
                  "a run; re-run experiments/stage3_poles.py to regenerate it")
            continue
        by_model[model] = {r["query"]: r for r in record.per_item}
    return by_model


def paid_productivity(strategy_record: dict) -> float | None:
    """Share of paid positions whose token differs from NoRAG's argmax.

    1.0 means every unit of epsilon changed the output. Near 0 means the budget
    was spent reproducing what the free path would have emitted anyway.
    """
    paid = strategy_record.get("paid_positions")
    emitted, norag = strategy_record.get("emitted"), strategy_record.get("norag_argmax")
    if not paid or not emitted or not norag:
        return None
    changed = sum(1 for i in paid if i < len(norag) and emitted[i] != norag[i])
    return changed / len(paid)


def grounding(strategy_record: dict, documents: list[str]) -> tuple[int, int]:
    """(clinical spans supported by a document, clinical spans total).

    Word-like spans only: a vocabulary has vetted those, whereas nothing can vet
    whether "197 mg" is a real dose, so counting doses here would measure the
    detector rather than the grounding.
    """
    text = strategy_record.get("text", "")
    clinical = strategy_record.get("clinical") or []
    if not text or not clinical or not documents:
        return 0, 0

    from dprag.medical_flags import find_medical_spans

    haystack = "\n".join(documents).lower()
    spans = [s for s in find_medical_spans(text) if s.kind == WORD_KIND]
    supported = sum(1 for s in spans if s.text.lower() in haystack)
    return supported, len(spans)


# --------------------------------------------------------------------------
# Gathering every (hypothesis, reference) pair once
# --------------------------------------------------------------------------

def gather(records, refs, poles_by_model):
    """Per-record pair inventory plus the list of pairs still needing BERTScore.

    Every pair in the run is planned first and scored in ONE call, rather than a
    call per record. `bert_score.score` loads the encoder on each invocation, so
    scoring record by record would load a 750M model eighty-seven times.
    """
    plan = {}
    missing = []
    for record, source_hash in records:
        model = record.param("gen_model", "unknown")
        poles = poles_by_model.get(model, {})
        cached = load_cache(record.path.stem, EXP.bertscore_model,
                            EXP.bertscore_rescale, source_hash)
        per_strategy = {}
        for name in record.metric("strategies", []):
            texts = {c: [None] * len(record.per_item) for c in COMPARISONS}
            scores = {c: list(cached.get(name, {}).get(c, [None] * len(record.per_item)))
                      for c in COMPARISONS}
            for c in COMPARISONS:
                if len(scores[c]) != len(record.per_item):
                    scores[c] = [None] * len(record.per_item)
            for i, row in enumerate(record.per_item):
                sr = row["by_strategy"].get(name)
                if not sr:
                    continue
                hyp = sr.get("text", "")
                pair_for = {
                    REFERENCE: refs.get(row["query"]),
                    NORAG: (poles.get(row["query"]) or {}).get("norag_text"),
                    RAG: (poles.get(row["query"]) or {}).get("rag_text"),
                }
                for c, other in pair_for.items():
                    if not hyp or not other:
                        continue
                    texts[c][i] = (hyp, other)
                    if scores[c][i] is None:
                        missing.append((record.path.stem, name, c, i, hyp, other))
            per_strategy[name] = {"texts": texts, "bert": scores}
        plan[record.path.stem] = {"record": record, "hash": source_hash,
                                  "strategies": per_strategy}
    return plan, missing


def fill_bertscore(plan, missing, batch_size):
    """Score every missing pair in one pass and write the caches back."""
    if not missing:
        print(f"BERTScore: all {sum(1 for _ in iter_pairs(plan))} pairs cached "
              f"({EXP.bertscore_model}, rescale={EXP.bertscore_rescale}).")
        return
    print(f"BERTScore: {len(missing)} pairs to score with {EXP.bertscore_model} "
          f"(rescale={EXP.bertscore_rescale}, batch_size={batch_size}).")
    print("           First run also downloads the encoder. Results are cached.")
    values = bertscore_f1([m[4] for m in missing], [m[5] for m in missing],
                          model=EXP.bertscore_model, rescale=EXP.bertscore_rescale,
                          batch_size=batch_size)
    for (stem, name, comparison, index, _h, _r), value in zip(missing, values):
        plan[stem]["strategies"][name]["bert"][comparison][index] = value
    touched = {m[0] for m in missing}
    for stem in sorted(touched):
        entry = plan[stem]
        save_cache(stem, EXP.bertscore_model, EXP.bertscore_rescale, entry["hash"],
                   {name: s["bert"] for name, s in entry["strategies"].items()})
    print(f"           cached into {paths.results_dir() / CACHE_DIR}")


def iter_pairs(plan):
    for entry in plan.values():
        for s in entry["strategies"].values():
            for c in COMPARISONS:
                for pair in s["texts"][c]:
                    if pair is not None:
                        yield pair


# --------------------------------------------------------------------------
# Scoring one (record, strategy) into the numbers both tables need
# --------------------------------------------------------------------------

def score_rows(plan, corpus_cache, damaged):
    """One dict per (record, strategy), carrying everything the tables print."""
    rows = []
    for stem, entry in sorted(plan.items()):
        record = entry["record"]
        key = (record.param("n_docs"), record.param("corpus_seed"))
        if key not in corpus_cache:
            corpus_cache[key] = load_corpus(limit=key[0], sample_seed=key[1])
        corpus = corpus_cache[key]

        for name, s in entry["strategies"].items():
            acc = {"rouge": {c: [] for c in COMPARISONS},
                   "bert": {c: [] for c in COMPARISONS}}
            clean = {"rouge": [], "bert": []}
            triggers, productive = [], []
            supported = total_spans = 0

            for i, row in enumerate(record.per_item):
                sr = row["by_strategy"].get(name)
                if not sr:
                    continue
                triggers.append(sr.get("trigger_rate", 0.0))
                p = paid_productivity(sr)
                if p is not None:
                    productive.append(p)
                docs = [corpus[j] for j, _ in row.get("docs", []) if j < len(corpus)]
                a, b = grounding(sr, docs)
                supported += a
                total_spans += b

                for c in COMPARISONS:
                    pair = s["texts"][c][i]
                    if pair is None:
                        continue
                    r = rouge_l_f1(*pair)
                    acc["rouge"][c].append(r)
                    value = s["bert"][c][i]
                    if value is not None:
                        acc["bert"][c].append(value)
                    if c == REFERENCE and not damaged.get(row["query"]):
                        clean["rouge"].append(r)
                        if value is not None:
                            clean["bert"].append(value)

            rows.append({
                "stem": stem, "config": name,
                "model": record.param("gen_model", "unknown"),
                "epsilon": float(record.param("gen_epsilon", 0.0)),
                "n": len(acc["rouge"][REFERENCE]),
                "trigger": mean_or_none(triggers),
                "rouge": acc["rouge"], "bert": acc["bert"],
                "clean": clean,
                "productive": mean_or_none(productive),
                "grounded": (supported, total_spans),
            })
    return rows


