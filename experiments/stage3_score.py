"""Everything computed after generation, from saved text.

The sweeps record and score nothing. This reads their output and produces the
quality and grounding numbers, none of which needs the generation GPU and none of
which can therefore cost a generation run when it breaks.

TWO METRICS, AND WHICH ONE DECIDES
----------------------------------
**ROUGE-L** counts a longest common subsequence of words. **BERTScore** embeds
tokens in context and matches them semantically, so `ibuprofen` and `Advil` score
high where ROUGE-L scores zero. The exponential mechanism resamples a token at
every paid position, so **changing the wording is what DP does** -- and a lexical
metric cannot separate "DP made the answer wrong" from "DP made it say the same
thing differently".

Both are printed. **BERTScore decides the dominance verdicts.** On this data
ROUGE-L has demonstrated it cannot separate configurations: every Llama value sits
in 0.11-0.13 with a half-width of 0.005, so letting it arbitrate would keep
producing "indistinguishable" from a ruler already known to be blunt. The proposal
also names BERTScore first in its quality dimension.

TWO TABLES, BECAUSE THEY ANSWER DIFFERENT QUESTIONS
---------------------------------------------------
**Quality** compares the answer against the doctor's reply. That is the axis the
proposal's 5.1 asks for.

**Grounding** locates the answer between two poles generated by
`stage3_poles.py` on the same documents: one with no documents, one with all of
them. This exists because of a specific objection -- "you skipped DP at 87% of
positions and the answer got better; of course it did" -- which a quality score
cannot answer, since a system ignoring every document could also score well.

THE POLE SIMILARITIES ARE REPORTED SEPARATELY, NOT ONLY AS THEIR DIFFERENCE
--------------------------------------------------------------------------
An earlier version printed only `lean = sim(answer, RAG pole) - sim(answer, NoRAG
pole)`. That single number conflates two opposite things, and on this data it
actively misleads. Decomposed at eps=40 on Llama, with ROUGE-L:

    config       trigger   vs NoRAG   vs RAG    lean
    baseline        0.0%     0.2780   0.2529  -0.0251
    B_k20_t0.7     66.3%     0.3831   0.2699  -0.1133
    A              87.0%     0.3716   0.3261  -0.0455
    B_k50_t0.5     95.8%     0.7181   0.2747  -0.4434

The NoRAG column rises with the trigger rate, because a skipped position emits
NoRAG's own token: a high-trigger configuration is partly *copying* the pole it is
being measured against. B_k50_t0.5's 0.718 is that effect at full strength, and
its -0.44 is a measurement of copying rather than of abandoning the documents.

The RAG column is nearly flat -- except for A, the only configuration that moves
towards the grounded pole at all (0.326 against baseline's 0.253). That has a
mechanism: A skips only where the two instances agree, so at every skipped
position NoRAG's token *is* RAG's token, and the answer tracks both poles at once.
The difference hides this and makes A look slightly worse than baseline.

Note that BERTScore does not remove the copying effect -- identical text scores at
the maximum under any similarity metric. What it removes is the *penalty* on the
RAG side for saying the same thing in different words.

DAMAGED REFERENCES
------------------
17.7% of the iCliniq references are truncated with a drug name eaten, and 12.5%
describe an attachment the model never sees (`dprag.chatdoctor.reference_damage`,
`docs/notes/reference-damage.md`). Under ROUGE-L the damage was measured and found
to move the mean by 1-2% relative, so the note concluded that reporting it beats
excluding 30% of the sample. That conclusion does not transfer automatically: a
semantic metric may lose more when the reference is missing a drug name. The last
section re-runs the comparison for both metrics so the report can state which.

COST AND THE CACHE
------------------
BERTScore runs a 750M encoder over roughly 8,000 pairs. Scores are cached under
`results/scores/`, stamped with the encoder, the rescaling flag, and a hash of the
source record. Any of the three changing invalidates the entry, because **a
BERTScore is meaningless without the encoder that produced it** -- a cache keyed on
the record name alone would silently print numbers from two different encoders in
one table, which is this project's characteristic failure: no exception, just a
plausible wrong number.

The cache is never written back into the generation records. `stage3_2_main.py`
records "Generation only ... so a scoring failure cannot cost a generation run",
and a scoring bug must not be able to damage fifteen hours of A100 output.

    uv run python experiments/stage3_score.py
"""

import glob
import hashlib
import json
import math
import statistics as st
from pathlib import Path

from dprag import paths, run_record
from dprag.chatdoctor import load_corpus, load_queries, reference_damage
from dprag.config import ExperimentConfig
from dprag.medical_flags import WORD_KIND
from dprag.quality import bertscore_f1, rouge_l_f1

RECORD_GLOB = "stage3_*"
POLES_GLOB = "stage3_poles_*"
CACHE_DIR = "scores"

# The three comparisons every answer takes part in.
REFERENCE, NORAG, RAG = "reference", "norag", "rag"
COMPARISONS = (REFERENCE, NORAG, RAG)


# --------------------------------------------------------------------------
# Cache
# --------------------------------------------------------------------------

def fingerprint(path: str) -> str:
    """Content hash of a record file.

    Content rather than mtime: the records are copied between the pod and here,
    and a copy changes the timestamp without changing a single answer. Hashing
    two megabytes is far cheaper than re-scoring a record that did not change.
    """
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def cache_file(stem: str) -> Path:
    return paths.results_dir() / CACHE_DIR / f"{stem}.json"


def load_cache(stem: str, model: str, rescale: bool, source_hash: str) -> dict:
    """Cached BERTScores for one record, or {} when the entry cannot be trusted.

    Returns strategy -> comparison -> list aligned with `record.per_item`.
    """
    path = cache_file(stem)
    if not path.exists():
        return {}
    try:
        blob = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    if (blob.get("bertscore_model") != model
            or blob.get("bertscore_rescale") != rescale
            or blob.get("source_sha256") != source_hash):
        return {}
    return blob.get("scores", {})


def save_cache(stem: str, model: str, rescale: bool, source_hash: str,
               scores: dict) -> None:
    path = cache_file(stem)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps({
        "bertscore_model": model,
        "bertscore_rescale": rescale,
        "source_sha256": source_hash,
        "note": ("BERTScore only. Derived from the named record; delete freely, "
                 "it is regenerated by experiments/stage3_score.py. Scores from "
                 "different encoders are not comparable, which is why the "
                 "encoder is stamped here."),
        "scores": scores,
    }, indent=1), encoding="utf-8")


# --------------------------------------------------------------------------
# Small statistics
# --------------------------------------------------------------------------

def ci95(values: list[float]) -> tuple[float, float]:
    """Mean and half-width. A mean without one invites reading noise as a result."""
    if len(values) < 2:
        return (values[0] if values else 0.0), 0.0
    return st.mean(values), 1.96 * st.stdev(values) / math.sqrt(len(values))


def mean_or_none(values: list[float]) -> float | None:
    return st.mean(values) if values else None


def fmt(value: float | None, spec: str = "%.4f") -> str:
    return "n/a" if value is None else spec % value


